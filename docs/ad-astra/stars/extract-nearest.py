#!/usr/bin/env python3
"""Build docs/ad-astra/prototype/starcat.js: the known star systems within 20
light-years, for the Ad Astra star map (AA-B6).

Source: Wikipedia, "List of nearest stars" (wikitext, CC BY-SA 4.0). Usage:
  curl -sS -A "hf-fan-mockup/1.0" -o nearest.wiki \
    "https://en.wikipedia.org/w/index.php?title=List_of_nearest_stars&action=raw"
  python3 docs/ad-astra/stars/extract-nearest.py nearest.wiki

Each system: name, distance (ly), position in light-years in GALACTIC
coordinates (x toward the galactic centre, y along rotation, z out of the
plane), and its stars' spectral classes. Read-only on the wikitext."""
import json, math, re, sys

src = open(sys.argv[1], encoding='utf-8').read()
start = src.index('{| class="wikitable mw-datatable')
end = src.index('\n|}', start)
table = src[start:end]
rows = table.split('\n|-')[2:]  # skip the two header rows

def cells_of(row):
    out = []
    for line in row.split('\n'):
        if line.startswith('|') and not line.startswith('|}') and not line.startswith('|+'):
            out.append(line[1:].strip())
        elif out:
            out[-1] += ' ' + line.strip()
    return out

def link_text(c):
    m = re.search(r'\[\[([^\]|]+)(?:\|([^\]]+))?\]\]', c)
    if m: return (m.group(2) or m.group(1)).strip()
    return re.sub(r'\{\{[^}]*\}\}|<[^>]+>', '', c.split('|')[-1]).strip()

num = lambda s: float(s.replace('−', '-').replace('–', '-'))
def coords(row):
    ra = re.search(r'\{\{RA\|(\d+)\|(\d+)\|([\d.]+)\}\}', row)
    de = re.search(r'\{\{DEC\|([+\-−–]?\d+)\|(\d+)\|([\d.]+)\}\}', row)
    if not (ra and de): return None
    h, m, s = (float(x) for x in ra.groups())
    dsign = -1 if de.group(1).strip()[0] in '-−–' else 1
    d, dm, ds = abs(num(de.group(1))), float(de.group(2)), float(de.group(3))
    return (h + m / 60 + s / 3600) * 15, dsign * (d + dm / 60 + ds / 3600)

def spectral(row):
    if re.search(r'white dwarf', row, re.I) and not re.search(r'star-color\|[OBAFGKM]', row): return 'D'
    m = re.search(r'star-color\|([A-Z])', row)
    if m: return m.group(1)
    m = re.search(r'(?:\||\s)([LTY])\s?\d', row)
    if m: return m.group(1)
    return None

def distance(row):
    # the distance cell is the first number carrying an uncertainty ({{br}}{{±..}});
    # the parallax cell comes later in the row and looks the same
    m = re.search(r'(?:^|\|)\s*([\d.]+)\s*(?:\{\{br\}\})?\s*\{\{±', row)
    return float(m.group(1)) if m else None

systems = []; cur = None; left = 0
for row in rows:
    cs = cells_of(row)
    if not cs: continue
    first = cs[0]
    if left <= 0:
        span = re.search(r'rowspan="?(\d+)', first)
        name = link_text(first)
        name = re.sub(r'\s*\(.*$', '', name).strip()
        cur = {'name': name, 'stars': [], 'ly': None, 'radec': None}
        systems.append(cur)
        left = int(span.group(1)) if span and 'colspan' not in first else 1
        comp_cells = cs[1:] if 'colspan' not in first else cs
    else:
        comp_cells = cs
    left -= 1
    d = distance(row)
    if d is not None and (cur['ly'] is None or d < cur['ly']): cur['ly'] = d
    rd = coords(row)
    if rd and not cur['radec']: cur['radec'] = rd
    sp = spectral(row)
    cname = link_text(comp_cells[0]) if comp_cells else cur['name']
    cur['stars'].append({'name': re.sub(r'\{\{[^}]*\}\}|[§$]', '', cname).strip(), 'cls': sp})

# equatorial -> galactic (J2000)
G = [[-0.0548755604, -0.8734370902, -0.4838350155], [0.4941094279, -0.4448296300, 0.7469822445], [-0.8676661490, -0.1980763734, 0.4559837762]]
out = []
for s in systems:
    if s['name'] in ('Solar System',) or not s['radec'] or not s['ly']: continue
    ra, dec = (math.radians(v) for v in s['radec'])
    e = [s['ly'] * math.cos(dec) * math.cos(ra), s['ly'] * math.cos(dec) * math.sin(ra), s['ly'] * math.sin(dec)]
    g = [sum(G[i][j] * e[j] for j in range(3)) for i in range(3)]
    kinds = [x['cls'] for x in s['stars'] if x['cls']]
    clean = lambda t: re.sub(r'<sup>2</sup>', '²', t.replace('&nbsp;', ' ')).strip()
    s['name'] = clean(s['name']); s['stars'] = [{**x, 'name': clean(x['name'])} for x in s['stars']]
    out.append({'name': s['name'], 'ly': round(s['ly'], 3), 'x': round(g[0], 3), 'y': round(g[1], 3), 'z': round(g[2], 3),
                'stars': [{'name': x['name'], 'cls': x['cls']} for x in s['stars']]})

out.sort(key=lambda s: s['ly'])
js = ('// GENERATED by docs/ad-astra/stars/extract-nearest.py - do not edit by hand.\n'
      '// The known star systems within 20 light-years (AA-B6). Positions in light-years,\n'
      '// galactic coordinates (x toward the galactic centre, y along rotation, z out of\n'
      '// the plane). Source: Wikipedia, "List of nearest stars" (CC BY-SA 4.0), 2026-11-14.\n'
      'export const STARCAT = ' + json.dumps(out, ensure_ascii=False, indent=0).replace('\n', '') + ';\n')
open('docs/ad-astra/prototype/starcat.js', 'w', encoding='utf-8').write(js)
print(len(out), 'systems;', sum(1 for s in out if len(s['stars']) > 1), 'multiple;', 'classes:', sorted({x['cls'] or '?' for s in out for x in s['stars']}))
for s in out[:6] + out[-3:]: print(' ', s['name'], s['ly'], [x['cls'] for x in s['stars']])
missing = [s['name'] for s in out if any(not x['cls'] for x in s['stars'])]
print('components without a class:', len(missing), missing[:12])
print(' | '.join(f"{s['name']} {s['ly']}" for s in out))
