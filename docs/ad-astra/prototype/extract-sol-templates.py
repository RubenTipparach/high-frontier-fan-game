#!/usr/bin/env python3
"""Cut body clusters out of the real HF Sol board (the vendored planner data)
so Ad Astra's star systems are built from Sol's own structure instead of an
invented layout. Writes docs/ad-astra/prototype/sol-templates.js.

For each template: every node within R world px of the body's centre (in the
1400x900 board world), the edges among them, only the connected part holding
the most named sites, and the 'ports' (kept nodes that had an edge leaving the
cut) so the cluster can be wired into a new system.
Run from the repo root: python3 docs/ad-astra/prototype/extract-sol-templates.py
"""
import json, math, collections, os

ROOT = os.path.join(os.path.dirname(__file__), '..', '..', '..')
d = json.load(open(os.path.join(ROOT, 'vendor/hf-mission-planner/assets/data-hf4.json')))
P = d['points']
W, H = 1400, 900
adj = collections.defaultdict(set)
for e in d['edges']:
    a, b = e.split(':')
    adj[a].add(b); adj[b].add(a)
xy = lambda k: (P[k]['x'] * W, P[k]['y'] * H)


def centroid(prefixes):
    ks = [k for k, p in P.items() if any(p.get('siteName', '').lower().startswith(x) for x in prefixes)]
    return (sum(xy(k)[0] for k in ks) / len(ks), sum(xy(k)[1] for k in ks) / len(ks))


def cut(name, centre, R, drop_names=()):
    inside = {k for k in P if math.dist(xy(k), centre) <= R
              and not any(P[k].get('siteName', '').lower().startswith(x) for x in drop_names)}
    # connected components inside the cut; keep the one with the most sites
    seen, comps = set(), []
    for k in inside:
        if k in seen: continue
        comp, q = set(), [k]
        while q:
            n = q.pop()
            if n in comp: continue
            comp.add(n); seen.add(n)
            q.extend(m for m in adj[n] if m in inside and m not in comp)
        comps.append(comp)
    keep = max(comps, key=lambda c: (sum(1 for k in c if 'siteName' in P[k]), len(c)))
    ids = sorted(keep, key=lambda k: (xy(k)[1], xy(k)[0]))
    idx = {k: i for i, k in enumerate(ids)}
    nodes = []
    for k in ids:
        p = P[k]; x, y = xy(k)
        n = {'t': p['type'], 'x': round(x - centre[0], 1), 'y': round(y - centre[1], 1)}
        if 'siteName' in p: n['n'] = p['siteName']
        if p.get('landing'): n['land'] = p['landing']
        if p.get('flybyBoost'): n['fly'] = p['flybyBoost']
        nodes.append(n)
    edges = sorted({tuple(sorted((idx[a], idx[b]))) for a in keep for b in adj[a] if b in keep})
    ports = sorted({idx[k] for k in keep for m in adj[k] if m not in keep})
    print(f"{name:8s} nodes={len(nodes):3d} edges={len(edges):3d} ports={len(ports):2d} sites={[n.get('n') for n in nodes if 'n' in n]}")
    return {'nodes': nodes, 'edges': [list(e) for e in edges], 'ports': ports}


T = {
    # the synthetic Jupiter body sits on the +4 gravity-assist Lagrange (planner-map.js)
    # R 160 keeps all four Galilean moons connected through the giant's well;
    # Sylvia and its moonlets are a main-belt asteroid system, not Jupiter's
    'jupiter': cut('jupiter', (0.337 * W, 0.429 * H), 160, drop_names=('sylvia', 'remus', 'romulus')),
    'mars': cut('mars', centroid(['mars', 'phobos', 'deimos']), 100),
    'mercury': cut('mercury', centroid(['mercury']), 55, drop_names=('venus', 'hathor')),
    'ceres': cut('ceres', centroid(['ceres']), 70),
}
out = os.path.join(os.path.dirname(__file__), 'sol-templates.js')
with open(out, 'w') as f:
    f.write('// GENERATED by extract-sol-templates.py from the vendored HF Sol board\n')
    f.write('// (vendor/hf-mission-planner/assets/data-hf4.json). Body clusters cut out of\n')
    f.write('// Sol so Ad Astra systems are built from Sol\'s own structure. Coordinates are\n')
    f.write('// relative to the body centre, in 1400x900 board-world px. Do not hand-edit.\n')
    f.write('export const SOL_TEMPLATES = ' + json.dumps(T, separators=(',', ':')) + ';\n')
print('wrote', out, os.path.getsize(out), 'bytes')
