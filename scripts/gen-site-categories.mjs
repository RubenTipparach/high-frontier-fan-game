// Generate data/site-categories.js from data/site-flags.json + data/sites.js.
//
// site-flags.json is keyed by normalized site NAME (see
// scripts/extract-site-flags.py); the engine + shared futures checkers need
// the same categories keyed by data/sites.js site IDs, in a pure ES data
// module both the client and the server can import (no JSON fetch, no
// node:fs). Re-run after a site-flags or sites.js change:
//
//   node scripts/gen-site-categories.mjs
//
// The lookup mirrors js/game/planner-map.js#lookupFlags: exact normalized
// name first, then the body-group fallback (first word of the name).

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SITES } from '../data/sites.js';
import { normalizeSiteName, slugify } from '../data/planner-ids.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const flagsDoc = JSON.parse(readFileSync(join(root, 'data', 'site-flags.json'), 'utf8'));

function lookupFlags(siteName) {
  if (!siteName) return {};
  const key = normalizeSiteName(siteName);
  if (key && flagsDoc.sites && flagsDoc.sites[key]) return flagsDoc.sites[key];
  if (key) {
    const grp = key.split(' ')[0];
    if (flagsDoc.groups && flagsDoc.groups[grp]) return flagsDoc.groups[grp];
  }
  return {};
}

// Each site lands under BOTH its data/sites.js id (underscored) and its wire
// slug (the planner's makeRefId = slugify(name), hyphenated) - the engine's
// state maps (factories / colonies / discs / positions) key by the wire slug,
// while the curated tables key by the sites.js id. Both must resolve.
const cats = { astrobiology: [], submarine: [], atmospheric: [], spaceElevator: [] };
for (const s of SITES) {
  const f = lookupFlags(s.name);
  const forms = [...new Set([s.id, slugify(s.name)])];
  if (f.astrobiology) cats.astrobiology.push(...forms);
  if (f.submarine) cats.submarine.push(...forms);
  if (f.atmospheric) cats.atmospheric.push(...forms);
  if (f.spaceElevator) cats.spaceElevator.push(...forms);
}

const stamp = 'Generated by scripts/gen-site-categories.mjs - do not hand-edit.';
const body = `// Site categories by data/sites.js id, derived from the site manifest's
// flag table (data/site-flags.json). ${stamp}
//
// Pure data: imported by BOTH the server engine (Homesteading colony types,
// Atmospheric promotion colonies) and the shared futures checkers
// (data/future-goals.js), the same reason fuel-graph / support-chain live in
// data/. Aerostat sites are identified by id (the 5 floating cities carry
// 'aerostat' in their id), not a flag column.

export const SITE_CATEGORIES = ${JSON.stringify(cats, null, 2)};

const _sets = Object.fromEntries(
  Object.entries(SITE_CATEGORIES).map(([k, ids]) => [k, new Set(ids)]),
);

export function isAstrobiologySite(siteId) { return _sets.astrobiology.has(siteId); }
export function isSubmarineSite(siteId) { return _sets.submarine.has(siteId); }
export function isAtmosphericSite(siteId) { return _sets.atmospheric.has(siteId); }
export function isSpaceElevatorSite(siteId) { return _sets.spaceElevator.has(siteId); }
export function isAerostatSiteId(siteId) { return /aerostat/i.test(String(siteId || '')); }

// Colony location class for a site (the VP + promotion-colony read):
// submarine beats astrobiology when a site is both (endgame-scoring's rate
// order), else null for a plain site. Mirrors browse.js#colonyTypeOfSite.
export function colonyClassOfSite(siteId) {
  if (isSubmarineSite(siteId)) return 'submarine';
  if (isAstrobiologySite(siteId)) return 'astrobiology';
  return null;
}
`;

writeFileSync(join(root, 'data', 'site-categories.js'), body);
console.log('data/site-categories.js:',
  Object.entries(cats).map(([k, v]) => `${k}=${v.length}`).join(' '));
