#!/usr/bin/env node
// Generate data/site-tags.js from data/site-notes.json (the in-app site-notes
// export). Keeps only "tag" annotations, drops "message" notes and the "burns"
// tag, and folds them per node id2 into { lander, half, hazard, aerobrake }.
// Re-run when new tags are exported:  node scripts/gen-node-tags.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const raw = JSON.parse(readFileSync(resolve(__dirname, '..', 'data', 'site-notes.json'), 'utf8'));
const FLAG = { 'lander-burn': 'lander', 'half-burn': 'half', 'hazard': 'hazard', 'aero-break': 'aerobrake' };

const bySite = {};
for (const a of raw.annotations || []) {
  if (a.kind !== 'tag') continue;           // ignore "message" notes
  if (a.body === 'burns') continue;          // ignore the plain "burns" tag for now
  const flag = FLAG[a.body];
  if (!flag) continue;
  (bySite[a.site_id] || (bySite[a.site_id] = {}))[flag] = true;
}

const ids = Object.keys(bySite).sort();
const body = ids.map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(bySite[id])},`).join('\n');
const out = `// AUTO-GENERATED by scripts/gen-node-tags.mjs from data/site-notes.json - do
// not edit by hand. Player-curated node classifications from the in-app
// site-notes "tag" annotations. half-burn + lander-burn => half-lander; the
// plain "burns" tag and "message" notes are ignored. Keyed by a node's id2 ref.
export const NODE_TAGS = {
${body}
};

// Resolve a { lander, half, hazard, aerobrake } record to a map marker sprite
// name (matching assets/map-icons/), or null when it implies no marker.
export function spriteForTags(t) {
  if (!t) return null;
  if (t.aerobrake) return 'aerobrake';
  if (t.lander && t.half && t.hazard) return 'lander-half-hazard';
  if (t.lander && t.half) return 'lander-half';
  if (t.lander && t.hazard) return 'lander-hazard';
  if (t.lander) return 'lander';
  if (t.hazard) return 'hazard';
  return null;
}

// The server/data view of a node (its planner flags) in the same shape, for the
// "what the server thinks vs what players tagged" comparison in the popup.
export function serverTagsFor(node) {
  if (!node) return {};
  const t = {};
  if (node.landing != null) { t.lander = true; if (node.landing < 1) t.half = true; }
  if (node.hazard) t.hazard = true;
  return t;
}
`;
writeFileSync(resolve(__dirname, '..', 'data', 'node-tags.js'), out);
console.log(`wrote data/node-tags.js (${ids.length} tagged nodes)`);
