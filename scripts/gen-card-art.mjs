// Generates the patent-card background art for every deck in DECKS to
// assets/cards/<deck>/<cardId>-<front|back>.svg, plus the runtime manifest
// data/card-art.js. Run: node scripts/gen-card-art.mjs
//
// Original flat-vector illustrations in the colonist-art idiom (dark space
// gradient, seeded starfield, glowing subject), drawn from the shared kit in
// scripts/card-art/kit.mjs. Each face draws ITS OWN technology - the black
// back of a card is a different machine, so it gets a different picture.
//
// The art is a BACKGROUND ONLY (css/cards.css .has-bg-art): the card layout is
// untouched. See docs/card-art-guide.md.
//
// Deterministic: no Math.random() - the starfield is a seeded PRNG.
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compose } from './card-art/kit.mjs';
import * as thrusters from './card-art/thrusters.mjs';
import * as robonauts from './card-art/robonauts.mjs';
import * as refineries from './card-art/refineries.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

// Per deck: its faces, its ship mounts, and which faces are APPROVED to render
// in the game ('<cardId>:primary' / '<cardId>:secondary', or '*' for all).
// Show the user a rendered preview before approving (CLAUDE.md).
const DECKS = {
  thrusters: { ...thrusters, approved: new Set(['*']) },
  robonauts: { ...robonauts, approved: new Set(['*']) },
  refineries: { ...refineries, approved: new Set([]) },   // awaiting the user's sign-off
};

const manifest = {};
let count = 0;
for (const [deck, { ART, RIG = {}, approved }] of Object.entries(DECKS)) {
  mkdirSync(join(ROOT, 'assets', 'cards', deck), { recursive: true });
  for (const [key, draw] of Object.entries(ART)) {
    const [card, face] = key.split(':');
    const side = face === 'primary' ? 'front' : 'back';
    const rel = `assets/cards/${deck}/${card}-${side}.svg`;
    writeFileSync(join(ROOT, rel), compose(RIG, key, draw()));
    (manifest[card] ||= {})[face] = { src: rel, approved: approved.has('*') || approved.has(key) };
    count++;
  }
}

writeFileSync(join(ROOT, 'data', 'card-art.js'), `// AUTO-GENERATED by scripts/gen-card-art.mjs - do not edit by hand.
// Card-body background art for patent cards, keyed by card id then face
// (primary = white front, secondary = black back). Only entries with
// approved: true render in the game; approve a deck's faces in the
// generator's DECKS table and re-run. Consumed by js/game/card-ui.js.
// See docs/card-art-guide.md.
export const CARD_ART = ${JSON.stringify(manifest, null, 2)};
`);
console.log(`wrote ${count} card art SVGs`);
