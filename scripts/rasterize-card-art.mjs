#!/usr/bin/env node
// Bake every approved SVG card art (data/card-art.js) into a flat WebP
// "texture" for Battery saver.
//
//   node scripts/rasterize-card-art.mjs            # only stale / missing ones
//   node scripts/rasterize-card-art.mjs --force    # re-render all
//
// Why: the card-body art is hand-authored SVG full of feGaussianBlur glows and
// feTurbulence grain. Every time a card is drawn (hand, stacks, Library grids,
// the auction) the browser re-runs those filters, which is real work on a
// phone. Battery saver swaps each SVG for the pre-rendered image instead
// (js/game/card-ui.js#cardArtUrl), so a card costs one image decode.
//
// Each texture is rendered by Chromium itself (the same engine that draws the
// SVG in game, so the filters look identical) at 2x the SVG's own size, which
// stays sharp on a 220px card on a high-density screen, then encoded to WebP
// with ImageMagick. Output sits beside its SVG as <name>-tex.webp, and the
// map from SVG to texture is written to data/card-art-textures.js. A texture
// that is missing simply falls back to its SVG, so a new card is never broken
// by forgetting to re-run this; re-run it after scripts/gen-card-art.mjs.

import { createRequire } from 'node:module';
import { execFileSync, execSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SCALE = 2;
const QUALITY = 82;
const force = process.argv.includes('--force');

function loadPlaywright() {
  const req = createRequire(import.meta.url);
  const candidates = ['playwright'];
  try { candidates.push(execSync('npm root -g', { encoding: 'utf8' }).trim() + '/playwright'); } catch {}
  candidates.push('/opt/node22/lib/node_modules/playwright');
  for (const c of candidates) {
    try { return req(c); } catch {}
  }
  console.error('Could not load Playwright (see scripts/screenshot.mjs for setup notes).');
  process.exit(2);
}

const textureSrcFor = (src) => src.replace(/\.svg$/i, '-tex.webp');

const { CARD_ART } = await import(path.join(ROOT, 'data/card-art.js'));
const srcs = [...new Set(Object.values(CARD_ART)
  .flatMap((faces) => Object.values(faces))
  .filter((a) => a && a.approved && /\.svg$/i.test(a.src))
  .map((a) => a.src))].sort();

const { chromium } = loadPlaywright();
const browser = await chromium.launch();
const tmp = mkdtempSync(path.join(tmpdir(), 'hf-tex-'));
const manifest = {};
let made = 0, kept = 0;
try {
  const page = await browser.newPage({ deviceScaleFactor: SCALE });
  for (const src of srcs) {
    const svgPath = path.join(ROOT, src);
    if (!existsSync(svgPath)) { console.warn(`missing ${src}, skipped`); continue; }
    const texSrc = textureSrcFor(src);
    const texPath = path.join(ROOT, texSrc);
    manifest[src] = texSrc;
    if (!force && existsSync(texPath) && statSync(texPath).mtimeMs >= statSync(svgPath).mtimeMs) { kept++; continue; }
    const head = readFileSync(svgPath, 'utf8').slice(0, 2000);
    const vb = /viewBox="\s*[-\d.]+\s+[-\d.]+\s+([\d.]+)\s+([\d.]+)\s*"/.exec(head);
    const w = Math.round(Number((/\bwidth="([\d.]+)"/.exec(head) || vb || [])[1]) || 300);
    const h = Math.round(Number((/\bheight="([\d.]+)"/.exec(head) || [])[1] || (vb && vb[2])) || 300);
    await page.setViewportSize({ width: w, height: h });
    await page.goto('file://' + svgPath);
    const png = path.join(tmp, 'tex.png');
    await page.screenshot({ path: png, omitBackground: true, clip: { x: 0, y: 0, width: w, height: h } });
    execFileSync('convert', [png, '-quality', String(QUALITY), '-define', 'webp:method=6', texPath]);
    made++;
  }
} finally {
  await browser.close();
  rmSync(tmp, { recursive: true, force: true });
}

const body = JSON.stringify(manifest, null, 2);
writeFileSync(path.join(ROOT, 'data/card-art-textures.js'),
  `// AUTO-GENERATED by scripts/rasterize-card-art.mjs - do not edit by hand.
// Battery saver card art: each approved SVG card art (data/card-art.js) mapped
// to a pre-rendered WebP texture of the same picture, so a card draws one image
// instead of re-running the SVG's blur / grain filters. Consumed by
// js/game/card-ui.js#cardArtUrl; an SVG missing here just keeps its SVG.
export const CARD_ART_TEXTURES = ${body};
`);
console.log(`${made} rendered, ${kept} up to date, ${Object.keys(manifest).length} in data/card-art-textures.js`);
